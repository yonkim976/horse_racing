"""Freeze the explicitly selected two models and pure, already-verified feature math."""

from pathlib import Path
import ast, hashlib, json, shutil

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
R = ROOT / "thoroughbred/research"


def sha(p):
    with p.open("rb") as f:
        return hashlib.file_digest(f, "sha256").hexdigest()


def definitions(path, names):
    source = path.read_text()
    tree = ast.parse(source)
    found = {}
    for n in tree.body:
        if isinstance(n, (ast.FunctionDef, ast.ClassDef)) and n.name in names:
            found[n.name] = ast.get_source_segment(source, n)
        if isinstance(n, ast.Assign):
            for t in n.targets:
                if isinstance(t, ast.Name) and t.id in names:
                    found[t.id] = ast.get_source_segment(source, n)
    assert set(names) == set(found), (path, set(names) - set(found))
    return "\n\n".join(found[n] for n in names)


def main():
    provenance = {}
    for meet in [1, 3]:
        source = R / f"20261024_training_state_v1/outputs/models/personal_t2_{meet}_2026"
        for name in ["model.txt", "metadata.json"]:
            dest = HERE / f"meet_{meet}_{name}"
            assert not dest.exists()
            shutil.copyfile(source / name, dest)
            provenance[str(dest.relative_to(ROOT))] = {
                "source": str((source / name).relative_to(ROOT)),
                "sha256": sha(dest),
            }
    state = R / "20261022_dynamic_race_model_v1/state.py"
    section = R / "20261009_section_style_finish_v1/run.py"
    gate = R / "20261009_gate_front_late_v1/run.py"
    env = R / "20261008_profile_environment_ablation_v1/run.py"
    training = R / "20261024_training_state_v1/build_features.py"
    pure = HERE / "feature_math.py"
    header = '"""Frozen research feature math. Generated by prepare_assets.py; no I/O or training."""\nimport copy\nimport numpy as np\nimport pandas as pd\nfrom scipy.special import expit\n'
    header += "KEY=['race_key','program_no','horse_id']\nPARTS=['early','last600','late']\nCONFIG={'close_seconds':.15,'front_threshold':.4}\n"
    meta = json.loads((HERE / "meet_1_metadata.json").read_text())
    header += "DERIVED=" + repr(meta["features"][8:19]) + "\n"
    pure.write_text(
        (
            header
            + definitions(state, ["NAMES", "prior", "propagate", "Filter", "generate"])
            + "\n\n"
            + definitions(section, ["slots", "values", "average", "historical_features"])
            + "\n\nhistory_values = values\n\n"
            + definitions(gate, ["EVENTS", "conditional_profiles", "gate_features"])
            + "\n\n"
            + definitions(env, ["profile_frame"])
            + "\n"
        )
        .replace("S.values(", "history_values(")
        .replace("S.average(", "average(")
    )
    query_ast = ast.parse(training.read_text())
    queries = {}
    for n in query_ast.body:
        if isinstance(n, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id in ["DAILY_SQL", "WINDOW_SQL"] for t in n.targets
        ):
            queries[n.targets[0].id] = ast.literal_eval(n.value)
    for name, query in queries.items():
        (HERE / (name.lower() + ".sql")).write_text(query)
    probability = R / "20261022_probability_comparison_v1/probability.py"
    assert not (HERE / "probability.py").exists()
    shutil.copyfile(probability, HERE / "probability.py")
    (HERE / "asset_provenance.json").write_text(
        json.dumps(
            {
                "selected_model": "personal_t2",
                "year": 2026,
                "model_copies": provenance,
                "math_sources": {
                    str(p.relative_to(ROOT)): sha(p)
                    for p in [state, section, gate, env, training, probability]
                },
                "generated_math_sha256": sha(pure),
                "new_training_fits": 0,
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n"
    )
    (HERE / "feature_contract.json").write_text(
        json.dumps(
            {
                "features": meta["features"],
                "count": len(meta["features"]),
                "basic_training": meta["features"][-18:-8],
                "personal_training": meta["features"][-8:],
                "personal_sources": [
                    "train_days14",
                    "train_minutes14",
                    "train_minutes_per_day14",
                    "train_days28",
                    "train_minutes28",
                    "train_gap_days28",
                ],
                "cutoff_days": 2,
                "eligible_meets": [1, 3],
                "prediction_year": 2026,
                "all_runner_roster_required": True,
                "missing_history_policy": "historical null/zero-count/prior state rules; no guessed observations",
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n"
    )


if __name__ == "__main__":
    main()
