-- Add reproducible, immutable model metadata and runner explanations.

ALTER TABLE public.prediction_runs
    ADD COLUMN publication_content_sha256 varchar(64),
    ADD COLUMN domain varchar(20),
    ADD COLUMN prediction_stage varchar(30),
    ADD COLUMN parent_prediction_run_id integer,
    ADD COLUMN registry_sha256 varchar(64),
    ADD COLUMN input_card_sha256 varchar(64),
    ADD COLUMN source_card_at_ms bigint,
    ADD COLUMN history_cutoff_date date,
    ADD COLUMN data_availability_status varchar(30),
    ADD COLUMN probability_contract varchar(100),
    ADD COLUMN combination_algorithm_version varchar(100),
    ADD CONSTRAINT uq_prediction_runs_publication_content_sha256
        UNIQUE (publication_content_sha256),
    ADD CONSTRAINT fk_prediction_runs_parent_prediction_run_id_prediction_runs
        FOREIGN KEY (parent_prediction_run_id)
        REFERENCES public.prediction_runs(id) ON DELETE RESTRICT,
    ADD CONSTRAINT ck_prediction_runs_domain
        CHECK (domain IS NULL OR domain IN ('thoroughbred', 'jeju')),
    ADD CONSTRAINT ck_prediction_runs_stage
        CHECK (
            prediction_stage IS NULL
            OR prediction_stage IN ('initial_card', 'pre_race_update')
        ),
    ADD CONSTRAINT ck_prediction_runs_availability
        CHECK (
            data_availability_status IS NULL
            OR data_availability_status IN ('complete', 'partial', 'not_available')
        );

CREATE INDEX ix_prediction_runs_parent_id
    ON public.prediction_runs (parent_prediction_run_id);

ALTER TABLE public.model_predictions
    ADD COLUMN a_rank_in_race integer,
    ADD COLUMN field_size integer,
    ADD COLUMN raw_a_top3_score double precision,
    ADD COLUMN raw_bc_top3_score double precision,
    ADD COLUMN raw_win_score double precision,
    ADD COLUMN raw_rank_score double precision,
    ADD COLUMN raw_order_score double precision,
    ADD COLUMN beta_set double precision,
    ADD COLUMN beta_order double precision,
    ADD COLUMN runner_identifier varchar(50),
    ADD COLUMN jockey_identifier varchar(50),
    ADD COLUMN trainer_identifier varchar(50),
    ADD COLUMN owner_identifier varchar(50),
    ADD COLUMN starter_status varchar(30),
    ADD COLUMN cancellation_status varchar(30),
    ADD COLUMN body_weight_kg double precision,
    ADD COLUMN body_weight_change_kg double precision,
    ADD COLUMN data_quality_flags_json text,
    ADD CONSTRAINT ck_model_predictions_positive_rank
        CHECK (a_rank_in_race IS NULL OR a_rank_in_race > 0),
    ADD CONSTRAINT ck_model_predictions_positive_field_size
        CHECK (field_size IS NULL OR field_size > 0);

CREATE TABLE public.prediction_model_components (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_run_id integer NOT NULL,
    component varchar(30) NOT NULL,
    model_version varchar(150) NOT NULL,
    candidate_name varchar(100) NOT NULL,
    artifact_sha256 varchar(64) NOT NULL,
    metadata_sha256 varchar(64),
    algorithm_version varchar(100),
    parameters_json text NOT NULL,
    CONSTRAINT fk_prediction_model_components_prediction_run_id_prediction_runs
        FOREIGN KEY (prediction_run_id)
        REFERENCES public.prediction_runs(id) ON DELETE RESTRICT,
    CONSTRAINT uq_prediction_model_components_run_component
        UNIQUE (prediction_run_id, component)
);

CREATE INDEX ix_prediction_model_components_run_id
    ON public.prediction_model_components (prediction_run_id);

CREATE TABLE public.model_prediction_explanations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_prediction_id integer NOT NULL,
    component varchar(30) NOT NULL,
    feature_name varchar(150) NOT NULL,
    readable_feature_name varchar(150) NOT NULL,
    feature_value_json text NOT NULL,
    field_percentile double precision,
    contribution_direction varchar(10) NOT NULL,
    contribution_value double precision NOT NULL,
    contribution_rank integer NOT NULL,
    explanation_type varchar(30) NOT NULL,
    explanation_method varchar(50) NOT NULL,
    source_cutoff_at_ms bigint,
    CONSTRAINT fk_model_prediction_explanations_model_prediction_id_model_predictions
        FOREIGN KEY (model_prediction_id)
        REFERENCES public.model_predictions(id) ON DELETE RESTRICT,
    CONSTRAINT uq_model_prediction_explanations_direction_rank
        UNIQUE (
            model_prediction_id,
            component,
            contribution_direction,
            contribution_rank
        ),
    CONSTRAINT ck_model_prediction_explanations_direction
        CHECK (contribution_direction IN ('positive', 'negative')),
    CONSTRAINT ck_model_prediction_explanations_rank
        CHECK (contribution_rank BETWEEN 1 AND 3),
    CONSTRAINT ck_model_prediction_explanations_type
        CHECK (
            explanation_type IN (
                'interpretable',
                'categorical_model_effect',
                'data_quality_flag'
            )
        ),
    CONSTRAINT ck_model_prediction_explanations_percentile
        CHECK (field_percentile IS NULL OR field_percentile BETWEEN 0 AND 1)
);

CREATE INDEX ix_model_prediction_explanations_prediction_id
    ON public.model_prediction_explanations (model_prediction_id);

CREATE TRIGGER trg_prediction_model_components_immutable
BEFORE UPDATE OR DELETE ON public.prediction_model_components
FOR EACH ROW EXECUTE FUNCTION public.prevent_prediction_ledger_mutation();

CREATE TRIGGER trg_model_prediction_explanations_immutable
BEFORE UPDATE OR DELETE ON public.model_prediction_explanations
FOR EACH ROW EXECUTE FUNCTION public.prevent_prediction_ledger_mutation();

ALTER TABLE public.prediction_model_components ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.model_prediction_explanations ENABLE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE public.prediction_model_components
    FROM PUBLIC, anon, authenticated;
REVOKE ALL PRIVILEGES ON TABLE public.model_prediction_explanations
    FROM PUBLIC, anon, authenticated;
REVOKE ALL PRIVILEGES ON SEQUENCE public.prediction_model_components_id_seq
    FROM PUBLIC, anon, authenticated;
REVOKE ALL PRIVILEGES ON SEQUENCE public.model_prediction_explanations_id_seq
    FROM PUBLIC, anon, authenticated;
