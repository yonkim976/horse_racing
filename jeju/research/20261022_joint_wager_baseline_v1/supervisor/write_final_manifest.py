"""Seal this study's file inventory and recheck referenced source hashes."""
import hashlib
import json
import shutil
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
STUDY = HERE.parent
ROOT = HERE.parents[3]
DESTINATION = STUDY / 'FINAL_MANIFEST.json'


def sha(path):
    h = hashlib.sha256()
    with path.open('rb') as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def main():
    assert not DESTINATION.exists(), 'Refusing to replace a finalized manifest.'
    checked = {}
    for filename, field in [('SESSION_START.json', 'sources'),
                            ('SOURCE_REVIEW.json', 'sources'),
                            ('MODEL_REFERENCES.json', 'references')]:
        content = json.loads((HERE / filename).read_text())
        for item in content[field]:
            source = (ROOT / item['path']).resolve()
            assert source.is_relative_to(ROOT)
            digest = sha(source)
            assert digest == item['sha256'], source
            checked[str(source.relative_to(ROOT))] = digest
    report = json.loads((STUDY / 'experiment/outputs/report.json').read_text())
    assert report['code_sha256'] == sha(STUDY / 'experiment/baseline.py')
    assert report['plan_sha256'] == sha(STUDY / 'experiment/PLAN.md')
    assert json.loads((HERE / 'RESULT_REVIEW.json').read_text())['passed']
    assert json.loads((HERE / 'CHOICE_REVIEW.json').read_text())['passed']
    files = []
    for path in sorted(STUDY.rglob('*')):
        assert not path.is_symlink(), path
        if path.is_file():
            files.append(dict(path=str(path.relative_to(STUDY)), size_bytes=path.stat().st_size,
                              sha256=sha(path)))
    base_size = sum(item['size_bytes'] for item in files)
    groups = {}
    for item in files:
        group = item['path'].split('/')[0]
        groups[group] = groups.get(group, 0) + item['size_bytes']
    payload = dict(
        finalized_at_utc=datetime.now(timezone.utc).isoformat(),
        study_directory=str(STUDY),
        storage_budget_bytes=300000000,
        logical_file_bytes_excluding_this_manifest=base_size,
        manifest_size_bytes=0,
        total_new_file_bytes_including_manifest=0,
        new_file_count_including_manifest=len(files) + 1,
        disk_free_bytes_at_measurement=shutil.disk_usage(STUDY).free,
        byte_accounting='logical regular-file sizes including documentation, code, preflight audit history and generated bytecode; existing referenced data not copied',
        self_hash_omitted=True,
        sources_rehashed_unchanged=checked,
        bytes_by_top_level_path_excluding_manifest=groups,
        files=files)
    for _ in range(10):
        encoded = (json.dumps(payload, ensure_ascii=False, indent=2) + '\n').encode('utf-8')
        size = len(encoded)
        if payload['manifest_size_bytes'] == size and payload['total_new_file_bytes_including_manifest'] == base_size + size:
            break
        payload['manifest_size_bytes'] = size
        payload['total_new_file_bytes_including_manifest'] = base_size + size
    else:
        raise AssertionError('Manifest size accounting did not stabilize.')
    assert base_size + size < payload['storage_budget_bytes']
    with DESTINATION.open('xb') as handle:
        handle.write(encoded)
    actual_size = sum(path.stat().st_size for path in STUDY.rglob('*') if path.is_file())
    assert actual_size == payload['total_new_file_bytes_including_manifest']
    print(json.dumps(dict(total_new_file_bytes=actual_size,
                          new_file_count=payload['new_file_count_including_manifest'],
                          disk_free_bytes=payload['disk_free_bytes_at_measurement'],
                          unchanged_references=len(checked),
                          manifest_sha256=sha(DESTINATION)), indent=2))


if __name__ == '__main__':
    main()
